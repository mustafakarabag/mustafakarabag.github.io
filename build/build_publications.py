"""Builds data/publications.js from build/publications.xlsx and the per-paper folders.

Spreadsheet columns: PaperName, Category, Authors, Year, Venue, Folder, Keywords, Paper, Code, Video, Talk, Poster.
Each paper folder (build/papers/<Folder>/) holds abstract.txt and optionally media/<figure> + media/caption.txt.
Figures are copied to media/<Folder>/. Only the standard library is needed.
"""
import json, re, shutil, zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sheet_path = root / "build/publications.xlsx"
papers_dir = root / "build/papers"
M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
LINK_COLUMNS = ["Paper", "Code", "Video", "Talk", "Poster"]
FIGURE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".mp4", ".webm", ".svg"}

def read_rows(path):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        shared = ["".join(t.text or "" for t in si.iter(M + "t"))
                  for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(M + "si")]
    rows = []
    for r in ET.fromstring(z.read("xl/worksheets/sheet1.xml")).iter(M + "row"):
        cells = {}
        for c in r.findall(M + "c"):
            col = re.match("[A-Z]+", c.get("r")).group()
            v, t = c.find(M + "v"), c.get("t")
            if t == "inlineStr":
                cells[col] = "".join(x.text or "" for x in c.iter(M + "t"))
            elif v is not None:
                cells[col] = shared[int(v.text)] if t == "s" else v.text
        rows.append(cells)
    header = {col: name.strip() for col, name in rows[0].items()}
    return [{header[c]: v.strip() for c, v in r.items() if c in header} for r in rows[1:]]

def read_text(path):
    return re.sub(r"\s+", " ", path.read_text(encoding="utf-8")).strip() if path.exists() else ""

def display_tag(t):
    return " ".join("-".join(p.capitalize() for p in w.split("-")) for w in t.split())

papers = []
for row in read_rows(sheet_path):
    if not row.get("PaperName"):
        continue
    folder = row.get("Folder", "")
    pdir = papers_dir / folder
    media, caption = None, ""
    figures = sorted(f for f in (pdir / "media").glob("*") if f.suffix.lower() in FIGURE_EXT) if (pdir / "media").is_dir() else []
    if figures:
        dest = root / "media" / folder
        dest.mkdir(parents=True, exist_ok=True)
        shutil.copy2(figures[0], dest / figures[0].name)
        media = f"media/{folder}/{figures[0].name}"
        caption = read_text(pdir / "media/caption.txt")
    tags = [display_tag(k) for k in row.get("Keywords", "").split(",") if k.strip()]
    papers.append(dict(
        year=int(row["Year"]), title=row["PaperName"],
        authors=[a.strip() for a in row.get("Authors", "").split(",") if a.strip()],
        venue=row.get("Venue", ""), links={k: row[k] for k in LINK_COLUMNS if row.get(k)},
        abstract=read_text(pdir / "abstract.txt"), tags=sorted(set(tags)), media=media, caption=caption))

papers.sort(key=lambda p: -p["year"])
(root / "data/publications.js").write_text(
    "// Generated by build/build_publications.py. Do not edit by hand.\nconst PUBLICATIONS = "
    + json.dumps(papers, indent=1, ensure_ascii=False) + ";\n")
print(len(papers), "papers;", sum(1 for p in papers if p["media"]), "with figures;",
      sum(1 for p in papers if not p["abstract"]), "without abstract;", sum(1 for p in papers if not p["links"]), "without links")
